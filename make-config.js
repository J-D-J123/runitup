// Reads .env and writes config.js with the PUBLIC values only (URL + publishable key).
// The secret key is never copied. Run: node make-config.js
const fs = require("fs");

const env = {};
for (const line of fs.readFileSync(".env", "utf8").split(/\r?\n/)) {
  const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
  if (m && !line.trim().startsWith("#")) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}

const url = env.SUPABASE_URL, key = env.SUPABASE_PUBLISHABLE_KEY;
if (!url || !key) { console.error("Set SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY in .env"); process.exit(1); }
if (!key.startsWith("sb_publishable_") && !key.startsWith("eyJ")) {
  console.error("SUPABASE_PUBLISHABLE_KEY doesn't look like a publishable/anon key. Refusing to write config.js.");
  process.exit(1);
}

fs.writeFileSync("config.js",
  "// Generated by make-config.js from .env. Public values only.\n" +
  "window.RUNCLUB_CONFIG = " + JSON.stringify({ url, key }) + ";\n");
console.log("Wrote config.js");
